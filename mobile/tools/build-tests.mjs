#!/usr/bin/env node
/**
 * Mentor test upload → app bundle.
 * Reads redesign/tests/ and generates src/data/uploadedTests.ts.
 *
 * Two formats:
 *  A) MCQ test:  redesign/tests/<name>.json          (interactive, auto-graded)
 *  B) Paper test redesign/tests/<folder>/meta.json   (question paper pages as
 *     images + answer key pages + optional marking scheme pages)
 *
 * Batch publishing: both formats accept "batches": ["Super 30", ...].
 * Use ["All Batches"] (default) to publish to everyone. Only students whose
 * batch is listed will see the test in their Tests tab.
 */
import { readdirSync, readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const testsDir = resolve(here, '../../tests');
const assetsDir = join(here, '../src/tests-assets');
const outFile = join(here, '../src/data/uploadedTests.ts');

const mcqTests = [];
const paperTests = [];
const paperRequires = []; // {testIndex, field, relPath}

// A) root-level MCQ json files
for (const f of readdirSync(testsDir).filter((x) => x.endsWith('.json')).sort()) {
  const t = JSON.parse(readFileSync(join(testsDir, f), 'utf8'));
  if (!t.id || !t.title || !Array.isArray(t.questions) || !t.questions.length) {
    console.error(`❌ ${f}: id, title and questions[] are required`); process.exit(1);
  }
  for (const q of t.questions) {
    if (!q.correctOptionId) { console.error(`❌ ${f}: question ${q.id} missing correctOptionId (answer key)`); process.exit(1); }
  }
  t.batches = Array.isArray(t.batches) && t.batches.length ? t.batches : ['All Batches'];
  mcqTests.push(t);
  console.log(`✅ ${f} → ${t.title} (${t.questions.length} MCQs, batches: ${t.batches.join(', ')})`);
}

// B) folder-based paper tests
for (const dir of readdirSync(testsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const metaPath = join(testsDir, dir, 'meta.json');
  if (!existsSync(metaPath)) continue;
  const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
  if (!meta.id || !meta.title) { console.error(`❌ ${dir}/meta.json: id and title are required`); process.exit(1); }
  meta.batches = Array.isArray(meta.batches) && meta.batches.length ? meta.batches : ['All Batches'];
  const destDir = join(assetsDir, dir);
  mkdirSync(destDir, { recursive: true });
  const idx = paperTests.length;
  const fields = ['paperPages', 'answerKeyPages', 'markingSchemePages'];
  for (const field of fields) {
    for (const img of meta[field] || []) {
      const src = join(testsDir, dir, img);
      if (!existsSync(src)) { console.error(`❌ ${dir}: missing image ${img}`); process.exit(1); }
      copyFileSync(src, join(destDir, img));
      paperRequires.push({ idx, field, rel: `../tests-assets/${dir}/${img}` });
    }
  }
  if (!(meta.paperPages || []).length) { console.error(`❌ ${dir}: paperPages must list at least one image`); process.exit(1); }
  paperTests.push(meta);
  console.log(`✅ ${dir}/ → ${meta.title} (batches: ${meta.batches.join(', ')})`);
}

// generate TS
const reqMap = new Map(); // idx -> field -> [rel]
for (const r of paperRequires) {
  if (!reqMap.has(r.idx)) reqMap.set(r.idx, new Map());
  const m = reqMap.get(r.idx);
  if (!m.has(r.field)) m.set(r.field, []);
  m.get(r.field).push(r.rel);
}
const arrTS = (list) => `[${list.map((rel) => `require('${rel}')`).join(', ')}]`;
const paperTS = paperTests.map((t, i) => {
  const m = reqMap.get(i) || new Map();
  const esc = (s) => JSON.stringify(s == null ? '' : s);
  return `{
  id: ${esc(t.id)},
  title: ${esc(t.title)},
  subject: ${esc(t.subject)},
  batches: ${JSON.stringify(t.batches)},
  durationMin: ${Number(t.durationMin) || 0},
  maxMarks: ${t.maxMarks != null ? Number(t.maxMarks) : 'undefined'},
  note: ${t.note != null ? esc(t.note) : 'undefined'},
  paperPages: ${arrTS(m.get('paperPages') || [])},
  answerKeyPages: ${arrTS(m.get('answerKeyPages') || [])},
  markingSchemePages: ${arrTS(m.get('markingSchemePages') || [])},
}`;
}).join(',\n');

const ts = `/** GENERATED by tools/build-tests.mjs — do NOT edit by hand. */
/* eslint-disable */
export type UploadedTestQuestion = { id: string; prompt: string; options: { id: string; text: string }[]; correctOptionId: string; explanation: string; marks: number };
export type UploadedTest = { id: string; title: string; subject: string; chapter: string; maxMarks: number; durationMin: number; negativeMarks?: number; markingScheme: string; batches: string[]; questions: UploadedTestQuestion[] };
export type UploadedPaperTest = { id: string; title: string; subject: string; batches: string[]; durationMin: number; maxMarks?: number; note?: string; paperPages: any[]; answerKeyPages: any[]; markingSchemePages: any[] };
export const uploadedTests: UploadedTest[] = ${JSON.stringify(mcqTests, null, 2)};
export const uploadedPaperTests: UploadedPaperTest[] = [
${paperTS}
];
`;
writeFileSync(outFile, ts);
console.log(`✔ ${mcqTests.length} MCQ test(s) + ${paperTests.length} paper test(s) → src/data/uploadedTests.ts`);
