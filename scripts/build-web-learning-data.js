#!/usr/bin/env node
/**
 * Builds the static web question bank from the native APK's canonical data.
 * This keeps Daily MCQ and Unlimited Practice content identical on both clients.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8');

function expressionBetween(source, marker, endMarker) {
  const start = source.indexOf(marker);
  if (start < 0) throw new Error(`Missing marker: ${marker}`);
  const expressionStart = start + marker.length;
  const end = source.indexOf(endMarker, expressionStart);
  if (end < 0) throw new Error(`Missing end marker after: ${marker}`);
  return source.slice(expressionStart, end).trim().replace(/;$/, '');
}

function evaluate(expression, label) {
  try {
    return Function(`"use strict"; return (${expression});`)();
  } catch (error) {
    throw new Error(`Could not parse ${label}: ${error.message}`);
  }
}

const bankSource = read('mobile/src/data/dailyMcqBank.ts');
const dailyMcqBank = evaluate(
  expressionBetween(bankSource, 'export const dailyMcqBank: DailyMcqQuestion[] = ', '\n];') + '\n]',
  'dailyMcqBank',
);

const catalogSource = read('mobile/src/data/icaiChapterCatalog.ts');
const chapterGroups = evaluate(
  expressionBetween(catalogSource, 'const chapterGroups: ChapterGroup[] = ', '\n\nexport const officialMcqChapterCatalog'),
  'chapterGroups',
);
const officialMcqChapterCatalog = chapterGroups
  .flatMap((group) => group.chapters.map(([chapterNumber, title]) => ({
    id: `${group.idPrefix}-${chapterNumber}`,
    subject: group.subject,
    paper: group.paper,
    section: group.section,
    part: group.part,
    module: group.module,
    chapterNumber,
    title,
    officialTitle: `Chapter ${chapterNumber}: ${title}`,
    displayTitle: [
      group.section,
      group.module,
      group.part?.startsWith('Part II') ? 'Part II' : undefined,
      `Chapter ${chapterNumber}: ${title}`,
    ].filter(Boolean).join(' · '),
    sourceUrl: group.sourceUrl,
  })))
  .map((chapter, catalogOrder) => ({ ...chapter, catalogOrder }));
const officialMcqChapterById = Object.fromEntries(officialMcqChapterCatalog.map((chapter) => [chapter.id, chapter]));

const metadataSource = read('mobile/src/data/mcqMetadata.ts');
const chapterIdByQuestionId = evaluate(
  expressionBetween(metadataSource, 'const chapterIdByQuestionId: Record<string, string> = ', '\n\nconst easyIds'),
  'chapter mappings',
);
const easyIds = new Set(evaluate(
  expressionBetween(metadataSource, 'const easyIds = new Set(', ');\n\nconst hardIds'),
  'easy IDs',
));
const hardIds = new Set(evaluate(
  expressionBetween(metadataSource, 'const hardIds = new Set(', ');\n\nexport const enrichMcqQuestion'),
  'hard IDs',
));

const questions = dailyMcqBank.map((question) => {
  const chapterId = chapterIdByQuestionId[question.id];
  const officialChapter = officialMcqChapterById[chapterId];
  if (!officialChapter) throw new Error(`Question ${question.id} has no official chapter mapping.`);
  if (officialChapter.subject !== question.subject) throw new Error(`Question ${question.id} is mapped across subjects.`);
  return {
    ...question,
    chapterId,
    chapter: officialChapter.displayTitle,
    chapterTitle: officialChapter.officialTitle,
    chapterNumber: officialChapter.chapterNumber,
    chapterModule: officialChapter.module,
    chapterSection: officialChapter.section,
    chapterOrder: officialChapter.catalogOrder,
    officialChapter,
    difficulty: hardIds.has(question.id) ? 'Hard' : easyIds.has(question.id) ? 'Easy' : 'Medium',
    kind: question.kind || 'normal',
  };
});

const mappedIds = new Set(Object.keys(chapterIdByQuestionId));
const missingMappings = dailyMcqBank.filter((question) => !mappedIds.has(question.id));
const staleMappings = [...mappedIds].filter((id) => !dailyMcqBank.some((question) => question.id === id));
if (missingMappings.length || staleMappings.length) {
  throw new Error(`Question mapping mismatch. Missing: ${missingMappings.map((q) => q.id)}; stale: ${staleMappings}`);
}

const manifestSource = read('mobile/src/data/icaiContentManifest.ts');
const manifest = evaluate(
  expressionBetween(manifestSource, 'export const icaiContentManifest = ', ' as const;'),
  'ICAI content manifest',
);

const payload = {
  revision: 'icai-may-2026-v1',
  questions,
  officialMcqChapterCatalog,
  manifest,
};
const output = `/* AUTO-GENERATED by scripts/build-web-learning-data.js. Do not edit directly. */\n` +
  `window.UMP_LEARNING_DATA = ${JSON.stringify(payload, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'learning-data.js'), output);
console.log(`Wrote learning-data.js with ${questions.length} APK-matched questions and ${officialMcqChapterCatalog.length} chapters.`);
